function yawToward(from, to) {
  let dx = to[0] - from[0], dz = to[2] - from[2]
  return Math.round(Math.atan2(-dx, dz) * 180 / Math.PI)
}

// Turn the player to face the hearth. The hearth is a registry constant, so this is the
// same yaw for every player on every world and it cannot fail for want of a ruin.
function facePath(server, player, name) {
  let hearth = global.valley.hearth()
  if (!hearth) return
  let yaw = yawToward([player.x, player.y, player.z], hearth)
  server.runCommandSilent('tp ' + name + ' ' + player.x + ' ' + player.y + ' ' + player.z + ' ' + yaw + ' 8')
}

// The compass is a lodestone compass pointed at the hearthstone from the registry — the
// flat grey block in the middle of the cottage floor that Q2's waystone goes on.
function kettleFarmCompass() {
  let hearth = global.valley.hearth()
  let tag = hearth
    ? 'LodestonePos:{X:' + hearth[0] + ',Y:' + hearth[1] + ',Z:' + hearth[2] + '},LodestoneDimension:"minecraft:overworld",LodestoneTracked:0b,'
    : ''
  return 'minecraft:compass{' + tag +
    'display:{Name:\'{"text":"Kettle Farm Compass","italic":false,"color":"gold"}\',' +
    'Lore:[\'{"text":"It points at the hearth.","color":"gray","italic":true}\']}}'
}

// Which way the farm is from spawn, in words, worked out once from the registry rather
// than stored from whatever direction a search happened to pick.
function hearthBearing() {
  let hearth = global.valley.hearth()
  let spawn = global.valley.site('spawn')
  if (!hearth || !spawn) return 'south'
  let dx = hearth[0] - spawn[0], dz = hearth[2] - spawn[2]
  let ns = dz > 0 ? 'south' : 'north'
  let ew = dx > 0 ? 'east' : 'west'
  if (Math.abs(dx) * 2 < Math.abs(dz)) return ns
  if (Math.abs(dz) * 2 < Math.abs(dx)) return ew
  return ns + '-' + ew
}

function tellWhere(server, name, where) {
  valleyDelay(90, s => {
    s.runCommandSilent('title ' + name + ' times 10 70 20')
    s.runCommandSilent('title ' + name + ' subtitle ' +
      JSON.stringify({ text: 'to the gate with her name on it. Your letter is in your hand.', color: 'gray' }))
    s.runCommandSilent('title ' + name + ' title ' +
      JSON.stringify({ text: 'Follow the road ' + (where || 'south'), color: 'gold' }))
    s.runCommandSilent('execute at ' + name + ' run playsound minecraft:block.note_block.bell master ' + name + ' ~ ~ ~ 1 1.2')
  })
}

// The objective is said ONCE per step, not every three seconds (the repeating
// bar was "really, really annoying"). Three steps: read the letter, walk to the
// farm, put the waystone on the hearthstone. After the letter is read a thin
// column of light rises from the hearthstone until the waystone is on it, so
// "the flat grey stone" is the one you can see from the gate.
function objectiveState(player) {
  let v = global.valley
  let team = v.teamId(player)
  if (v.isDone('q02', team)) return 'done'
  if (!v.isDone('q01', team)) return 'letter'
  let hearth = v.hearth()
  if (!hearth) return 'book'
  let d = Math.sqrt(Math.pow(hearth[0] - player.x, 2) + Math.pow(hearth[2] - player.z, 2))
  return d <= 12 ? 'hearth' : 'walk'
}

function objectiveLine(state) {
  if (state === 'letter') return { text: 'Read Josie\'s letter. It is in your hand: right-click.', color: 'gold' }
  if (state === 'book') return { text: 'Open the Quest Book (right-click it, or press J).', color: 'gold' }
  if (state === 'walk') return { text: 'The Homestead Waystone is in your bag. Follow the road and the compass to the farm.', color: 'gold' }
  if (state === 'hearth') return { text: 'Put the Homestead Waystone on the flat grey hearthstone, where the light rises, and name it Home.', color: 'gold' }
  return null
}

function objectiveLoop() {
  let server = global.valleyServer
  if (!server) return
  let v = global.valley
  global.valleyObjectiveSeen = global.valleyObjectiveSeen || {}
  let anyLit = false
  try {
    server.players.forEach(pl => {
      let name = v.pname(pl)
      let state = objectiveState(pl)
      if (state !== 'done' && state !== 'letter') anyLit = true
      if (global.valleyObjectiveSeen[name] === state) return
      global.valleyObjectiveSeen[name] = state
      let line = objectiveLine(state)
      if (line) server.runCommandSilent('title ' + name + ' actionbar ' + JSON.stringify(line))
    })
    // the hearth light: only while someone has read the letter and not yet placed the waystone
    let hearth = v.hearth()
    if (anyLit && hearth) {
      server.runCommandSilent('particle minecraft:end_rod ' + hearth[0] + '.5 ' + (hearth[1] + 1.2) + ' ' + hearth[2] + '.5 0.15 0.6 0.15 0.005 4 force')
    }
  } catch (err) {
    console.warn('[valley] objective loop: ' + err)
  }
  valleyDelay(20, objectiveLoop)
}

function startObjectiveLoop() {
  if (global.valleyObjectiveLoop) return
  global.valleyObjectiveLoop = true
  valleyDelay(40, objectiveLoop)
}

global.valley.orient = function (server, player) {
  let name = global.valley.pname(player)
  facePath(server, player, name)
  tellWhere(server, name, hearthBearing())
  server.runCommandSilent('give ' + name + ' ' + kettleFarmCompass() + ' 1')
  startObjectiveLoop()
}


function valleyFirstJoin(server, player, name) {
  // The letter, the deed and the kettle. Q1's task is READING the letter, which
  // valley_checks.js ticks off the right-click that opens the book.
  // Hotbar order is the tutorial: the letter lands in the selected slot.
  player.give(josieLetter())

  // Title card. Exactly the words in §2.
  server.runCommandSilent('title ' + name + ' times 20 90 30')
  server.runCommandSilent('title ' + name + ' subtitle ' +
    JSON.stringify({ text: 'Spring, Year One.', color: 'gray', italic: true }))
  server.runCommandSilent('title ' + name + ' title ' +
    JSON.stringify({ text: 'LITTLE KETTLE VALLEY', color: 'gold', bold: true }))
  // `~ ~ ~` resolves against the COMMAND SOURCE, and runCommandSilent runs as
  // the server (0 0 0, overworld) — so the sound has to be run `execute at`
  // the player or nobody hears it.
  server.runCommandSilent('execute at ' + name + ' run playsound minecraft:block.note_block.chime master ' + name + ' ~ ~ ~ 1 0.8')

  // The farm, the road, the signpost and the lit gate are ALREADY THERE. Spawn is fixed by
  // the world (scratch/master_build.sh runs `setworldspawn` from the registry with a yaw
  // that already faces the road), so nothing here places a block or moves the spawn point:
  // the first join hands over the kit, turns her round and tells her where to walk.
  let hearth = global.valley.hearth()
  let where = hearthBearing()

  player.give(Item.of('ftbquests:book'))
  player.give(Item.of(VALLEY.ITEM.deed))
  player.give(Item.of(VALLEY.ITEM.kettle))
  if (hearth) server.runCommandSilent('give ' + name + ' ' + kettleFarmCompass() + ' 1')
  valleyDelay(5, s => { try { facePath(s, player, name) } catch (err) {} })
  // A5: NO second title card here. tellWhere() fires one 4.5 seconds after the
  // LITTLE KETTLE VALLEY card, and two title cards that close together read as a
  // cutscene she cannot skip. The same destination, with coordinates, is chat line
  // two below, and the actionbar repeats it on every state change. tellWhere() is
  // still live on global.valley.orient for a player who asks to be re-pointed.
  startObjectiveLoop()

  // A5: ONE title card and at most TWO chat lines. The premise lives in the letter
  // itself; chat only says what to do (writer-brief rule 3 keeps the destination
  // line verbatim). The third line -- "right-click the Quest Book" -- moved to the
  // self-dismissing login nudge in PlayerEvents.loggedIn, so it can repeat for a
  // player who never opens the book and vanish forever for one who does.
  let lines = [
    [{ text: 'A letter from ', color: 'white' }, { text: 'Josie Kettle', color: 'gold' },
     { text: ' is in your bag. Read all four pages.', color: 'white' }]
  ]
  if (hearth) {
    lines.push([
      { text: 'The lantern road at your feet runs ' + where + ' to the farm. Follow it to the gate \u2014 the hearthstone is at ', color: 'white' },
      { text: hearth[0] + ' ' + hearth[1] + ' ' + hearth[2], color: 'gold' },
      { text: '.', color: 'white' }
    ])
  }
  lines.forEach((l, i) => {
    valleyDelay(20 + i * 20, s => s.runCommandSilent('tellraw ' + name + ' ' + JSON.stringify(l)))
  })

  // The world border and the two counters start where §12.5 says they do.
  if (global.valley.once('world_opened')) {
    server.runCommandSilent('worldborder set 1500')
    server.runCommandSilent('bossbar set valley:folk value 0')
    global.valley.setLampsLit(0)
  }
  console.info('[valley] first join handled for ' + name + '; the farm is ' + where +
               ' at ' + (hearth ? hearth.join(' ') : '??'))
}

