const SITES = (typeof global.valleySites !== 'undefined') ? global.valleySites : null
if (!SITES) {
  console.error('[valley] valley_sites.js did NOT load. Every coordinate in the pack lives ' +
                'in it; run tools/scripts/plan_town.py --site and re-sync the server.')
}

// A registry read that says which key was missing rather than returning undefined into
// arithmetic three files away.
function siteAt(path) {
  if (!SITES) return null
  let node = SITES
  let parts = String(path).split('.')
  for (let i = 0; i < parts.length; i++) {
    if (node === null || node === undefined) break
    node = node[parts[i]]
  }
  if (node === null || node === undefined) {
    console.warn('[valley] no "' + path + '" in valley_sites.json')
    return null
  }
  return node
}

// The forty posts, in LIGHTING ORDER, split by the quest that lights each one. A registry
// entry's `pos` is the FENCE; the cage lamp sits one block above it, and the lamp is what a
// setblock lights, so that is what these lists carry.
function lampHeads(route) {
  let out = []
  let list = (SITES && SITES.lamps) ? SITES.lamps : []
  for (let i = 0; i < list.length; i++) {
    if (route && list[i].route !== route) continue
    out.push([list[i].pos[0], list[i].pos[1] + 1, list[i].pos[2]])
  }
  return out
}

