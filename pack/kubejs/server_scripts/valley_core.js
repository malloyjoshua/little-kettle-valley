// Three hundred lines: RUIN_BEARINGS / RUIN_DIST / RUIN_SKIP, ruinSurface(), ruinSiteOk(),
// ruinPath(), placeRuin() and spawnSignpost(). Between them they searched eight bearings at
// three distances for somewhere flat enough to cut a pad, ran a datapack function that cut
